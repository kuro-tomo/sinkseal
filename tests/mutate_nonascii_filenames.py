#!/usr/bin/env python3
"""Mutation check for the non-ASCII file-name / fail-closed handling.

Deliberately injects one defect at a time into the relevant hook lines and verifies that
tests/test_nonascii_filenames.sh fails (= the mutant is killed). A surviving mutant means
the test would miss that particular way of breaking the hooks.

Usage: python3 tests/mutate_nonascii_filenames.py [--jobs N]
Exit:  0 = every mutant killed
       1 = at least one mutant survived
       2 = the checker itself is broken (unmutated control run failed, a mutant changed
           nothing, or no mutants were generated)

Mutants are generated by mechanically scanning every relevant line of the hooks (not by
hand-picking, which leaves gaps):
  - removing -z from a git call (quoted names come back)
  - removing `read -d ''` / `tr '\\0'` (NUL-delimited input is no longer parsed)
  - removing grep -F on a file name (name read as a regex)
  - removing :(literal) (name read as a pathspec)
  - disabling a "could not inspect" guard (inspection failure turns into a pass)
  - turning a "could not inspect" exit code into 0
  - dropping R (renames) from --diff-filter
  - pre-commit accepting a failed scan (so a trailer could wave it through)
The test runs the hooks under the C locale and, where present, a UTF-8 locale.
"""
import argparse
import concurrent.futures as cf
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEST = os.path.join("tests", "test_nonascii_filenames.sh")
HOOKS = [
    "hooks/rflag-scan.sh",
    "hooks/sink-scan.sh",
    "hooks/check-open-remediations.sh",
    "hooks/no-live-fire-check.sh",
    "hooks/sink-inventory-drift.sh",
    "hooks/pre-commit",
]
# Words that mark the "could not inspect" guards ADDED by this change. The older
# "pattern table not found" guards (also exit 1, also say "cannot run") are out of scope
# here; they are not about file names and are covered (sink-scan only) by smoke_test.sh.
GUARD_WORDS = ("Unable to inspect", "could not list the tracked files")


def is_comment(line):
    return line.lstrip().startswith("#")


def generate():
    """List of (name, relative path, line index, mutated line), built by scanning every line."""
    out = []
    for rel in HOOKS:
        text = open(os.path.join(ROOT, rel), encoding="utf-8").read()
        lines = text.split("\n")
        for i, ln in enumerate(lines):
            if is_comment(ln):
                continue
            tag = "%s:%d" % (rel, i + 1)
            nearby = "\n".join(lines[i:i + 4])
            if re.search(r"\bgit\b.* -z\b", ln):
                out.append(("%s drop -z from git (names get quoted)" % tag, rel, i, re.sub(r" -z\b", "", ln, count=1)))
            if "read -r -d ''" in ln:
                out.append(("%s drop -d '' from read (NUL input unparsed)" % tag, rel, i, ln.replace("read -r -d ''", "read -r")))
            if "tr '\\0' '\\n'" in ln:
                out.append(("%s drop tr '\\0' (NUL left in place)" % tag, rel, i, ln.replace("tr '\\0' '\\n'", "cat")))
            if "grep -iF" in ln:
                out.append(("%s drop grep -F (name read as regex)" % tag, rel, i, ln.replace("grep -iF", "grep -i")))
            if ":(literal)" in ln:
                out.append(("%s drop :(literal) (name read as pathspec)" % tag, rel, i, ln.replace(":(literal)", "")))
            if 'exit "${PIPESTATUS[0]}"' in ln:
                out.append(("%s discard git's exit status" % tag, rel, i, ln.replace('exit "${PIPESTATUS[0]}"', "exit 0")))
            if "--diff-filter=ACMR" in ln:
                out.append(("%s drop R from --diff-filter (renames skipped)" % tag, rel, i, ln.replace("ACMR", "ACM")))
            # pre-commit: accept a scan that could not run
            m = re.match(r'^(\s*)elif \[ "\$(rflag_rc|sink_rc|rem_rc)" -ne 0 \]; then$', ln)
            if m:
                out.append(("%s pre-commit stops refusing a failed %s" % (tag, m.group(2)), rel, i, "%selif false; then" % m.group(1)))
            # guard on a grep/git exit status: disable it (inspection failure -> pass)
            m = re.match(r'^(\s*)if \[ "\$gr" -(ne 0|ge 2) \]; then$', ln)
            if m and any(w in nearby for w in GUARD_WORDS):
                out.append(("%s disable the inspection-failure guard" % tag, rel, i, "%sif false; then" % m.group(1)))
            # guard on a git call that wraps the listing/diff: disable it
            m = re.match(r"^(\s*)if ! (.*); then$", ln)
            if m and "git " in m.group(2):
                out.append(("%s disable the git-failure guard" % tag, rel, i, "%s%s || true; if false; then" % (m.group(1), m.group(2))))
            # the exit code of a "could not inspect" stop: make it 0
            m = re.match(r"^(\s*)exit ([1-9])$", ln)
            if m and any(w in "\n".join(lines[max(0, i - 4):i]) for w in GUARD_WORDS):
                out.append(("%s turn the 'could not inspect' exit %s into 0" % (tag, m.group(2)), rel, i, "%sexit 0" % m.group(1)))
    return out


def run_mutant(m):
    name, rel, idx, new_line = m
    d = tempfile.mkdtemp()
    try:
        for sub in ("hooks", "lib", "tests"):
            shutil.copytree(os.path.join(ROOT, sub), os.path.join(d, sub))
        p = os.path.join(d, rel)
        lines = open(p, encoding="utf-8").read().split("\n")
        if lines[idx] == new_line:
            return name, "inert"
        lines[idx] = new_line
        open(p, "w", encoding="utf-8").write("\n".join(lines))
        r = subprocess.run(["bash", os.path.join(d, TEST)], capture_output=True, text=True, errors="replace")
        return name, ("killed" if r.returncode != 0 else "survived")
    finally:
        shutil.rmtree(d, ignore_errors=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", type=int, default=6)
    args = ap.parse_args()

    # Unmutated control run: if the test does not pass untouched, "all killed" would be meaningless.
    r = subprocess.run(["bash", os.path.join(ROOT, TEST)], capture_output=True, text=True, errors="replace")
    if r.returncode != 0:
        print("ABORT: the test fails on the unmutated hooks, so the mutation check would be meaningless.\n" + r.stdout[-600:])
        return 2
    print("control run: test passes on the unmutated hooks")

    mutants = generate()
    if not mutants:
        print("ABORT: no mutants were generated (checker bug)")
        return 2
    print("mutants generated: %d" % len(mutants))

    survived, inert = [], []
    with cf.ThreadPoolExecutor(max_workers=args.jobs) as ex:
        for name, res in ex.map(run_mutant, mutants):
            print(({"killed": "killed   ", "survived": "SURVIVED!!", "inert": "INERT!   "}[res]), name)
            if res == "survived":
                survived.append(name)
            elif res == "inert":
                inert.append(name)
    print("%d mutants: %d survived, %d inert" % (len(mutants), len(survived), len(inert)))
    if inert:
        return 2
    return 1 if survived else 0


if __name__ == "__main__":
    sys.exit(main())
